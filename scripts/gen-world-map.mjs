// Generates frontend/src/world-map-data.ts: one simplified SVG path of the
// world's landmasses (Natural Earth projection, Antarctica dropped) plus the
// projection constants the runtime needs to place pins at lat/lon.
//
// Dev-only; the output is committed so the site build needs no map libraries.
//   cd /tmp && mkdir mapgen && cd mapgen && npm i world-atlas topojson-client d3-geo
//   node <repo>/scripts/gen-world-map.mjs <repo>/frontend/src/world-map-data.ts
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
const require = createRequire(process.cwd() + '/')
const { feature } = require('topojson-client')
const { geoNaturalEarth1, geoPath } = require('d3-geo')
const topo = require('world-atlas/land-110m.json')

const out = process.argv[2]
const W = 1000, H = 520
const land = feature(topo, topo.objects.land)
// Drop Antarctica (and other polar slivers): keep polygons that reach above -58°.
const geom = land.type === 'FeatureCollection' ? land.features[0].geometry : land.geometry
const polys = geom.coordinates.filter(p => p[0].some(([, lat]) => lat > -58))
const geo = { type: 'Feature', geometry: { type: 'MultiPolygon', coordinates: polys } }

const projection = geoNaturalEarth1().fitExtent([[6, 6], [W - 6, H - 6]], geo)
const path = geoPath(projection).digits(1)
const d = path(geo)

const graticule = []
for (let lat = -60; lat <= 80; lat += 30) {
  const pts = []
  for (let lon = -180; lon <= 180; lon += 10) pts.push(projection([lon, lat]))
  graticule.push('M' + pts.map(p => p.map(v => v.toFixed(1)).join(' ')).join('L'))
}
for (let lon = -150; lon <= 180; lon += 30) {
  const pts = []
  for (let lat = -58; lat <= 84; lat += 6) pts.push(projection([lon, lat]))
  graticule.push('M' + pts.map(p => p.map(v => v.toFixed(1)).join(' ')).join('L'))
}

const [tx, ty] = projection.translate()
const ts = `// GENERATED by scripts/gen-world-map.mjs -- do not edit by hand.
// Natural Earth projection of Natural Earth 110m land (public domain).
export const MAP_W = ${W}
export const MAP_H = ${H}
export const MAP_SCALE = ${projection.scale()}
export const MAP_TX = ${tx}
export const MAP_TY = ${ty}
export const WORLD_LAND_PATH = ${JSON.stringify(d)}
export const WORLD_GRATICULE_PATH = ${JSON.stringify(graticule.join(''))}
`
writeFileSync(out, ts)
console.log('wrote', out, (ts.length / 1024).toFixed(1) + ' KB')
